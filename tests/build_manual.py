def prop(parent,name,value=None):
    el=OxmlElement(name)
    if value is not None:el.set(qn('w:val'),str(value))
    parent.append(el);return el


def format_run(run,rtl=True,size=None):
    run.font.name=FAMILY
    if size:run.font.size=Pt(size)
    rp=run._element.get_or_add_rPr()
    rf=rp.rFonts
    for key in ('ascii','hAnsi','eastAsia','cs'):rf.set(qn('w:'+key),FAMILY)
    for key in ('asciiTheme','hAnsiTheme','eastAsiaTheme','cstheme'):
        rf.attrib.pop(qn('w:'+key),None)
    prop(rp,'w:rtl',1 if rtl else 0)
    prop(rp,'w:lang').set(qn('w:bidi'),'fa-IR')

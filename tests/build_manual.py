def paragraph(doc,text,style=None,rtl=True,size=None):
    p=doc.add_paragraph(style=style)
    p.alignment=WD_ALIGN_PARAGRAPH.LEFT
    prop(p._p.get_or_add_pPr(),'w:bidi',1 if rtl else 0)
    format_run(p.add_run(text),rtl,size)
    return p


def table(doc,headers,rows):
    t=doc.add_table(rows=1,cols=2);t.alignment=WD_TABLE_ALIGNMENT.CENTER;t.autofit=False
    t.columns[0].width=Inches(2.25);t.columns[1].width=Inches(4.65)
    pr=t._tbl.tblPr;prop(pr,'w:bidiVisual',1)
    margins=prop(pr,'w:tblCellMar')
    for side in ('top','left','bottom','right'):
        e=prop(margins,'w:'+side);e.set(qn('w:w'),'65');e.set(qn('w:type'),'dxa')
    for i,values in enumerate([headers,*rows]):
        row=t.rows[0] if i==0 else t.add_row()
        prop(row._tr.get_or_add_trPr(),'w:cantSplit')
        if i==0:prop(row._tr.get_or_add_trPr(),'w:tblHeader')
        for j,text in enumerate(values):
            c=row.cells[j];c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            c.width=Inches(2.25 if j==0 else 4.65)
            p=c.paragraphs[0];p.alignment=WD_ALIGN_PARAGRAPH.LEFT
            prop(p._p.get_or_add_pPr(),'w:bidi',1)
            p.paragraph_format.space_after=Pt(1);p.paragraph_format.space_before=Pt(1)
            p.paragraph_format.line_spacing=1.08
            latin=all(ord(ch)<128 for ch in text)
            if latin:p.alignment=WD_ALIGN_PARAGRAPH.LEFT;prop(p._p.get_or_add_pPr(),'w:bidi',0)
            format_run(p.add_run(text),not latin,11)
            if i==0:
                sh=prop(c._tc.get_or_add_tcPr(),'w:shd');sh.set(qn('w:fill'),'EAEAEA')
    tail=doc.add_paragraph();tail.paragraph_format.space_after=Pt(0)
    tail.paragraph_format.line_spacing=Pt(1);format_run(tail.add_run(''),size=1)


def embed_font(path):
    ns='http://schemas.openxmlformats.org/wordprocessingml/2006/main'
    relns='http://schemas.openxmlformats.org/officeDocument/2006/relationships'
    package='http://schemas.openxmlformats.org/package/2006/relationships'
    with zipfile.ZipFile(path) as z:files={n:z.read(n) for n in z.namelist()}
    ft=etree.fromstring(files['word/fontTable.xml'])
    f=next((x for x in ft if x.get('{'+ns+'}name')==FAMILY),None)
    if f is None:f=etree.SubElement(ft,'{'+ns+'}font',{'{'+ns+'}name':FAMILY})
    key=uuid.UUID('12429A15-1A3B-4372-A627-649DF975103E')
    data=bytearray(FONT.read_bytes());obfuscator=key.bytes[::-1]
    for i in range(32):data[i]^=obfuscator[i%16]
    embed=etree.SubElement(f,'{'+ns+'}embedRegular')
    embed.set('{'+relns+'}id','rIdAria');embed.set('{'+ns+'}fontKey','{'+str(key).upper()+'}')
    embed.set('{'+ns+'}subsetted','false')
    relpath='word/_rels/fontTable.xml.rels'
    rels=etree.fromstring(files[relpath]) if relpath in files else etree.Element('{'+package+'}Relationships',nsmap={None:package})
    etree.SubElement(rels,'{'+package+'}Relationship',Id='rIdAria',Type=relns+'/font',Target='fonts/aria.odttf')
    types=etree.fromstring(files['[Content_Types].xml'])
    ct='http://schemas.openxmlformats.org/package/2006/content-types'
    etree.SubElement(types,'{'+ct+'}Default',Extension='odttf',ContentType='application/vnd.openxmlformats-officedocument.obfuscatedFont')
    files.update({'word/fontTable.xml':etree.tostring(ft,xml_declaration=True,encoding='UTF-8',standalone=True),
                  relpath:etree.tostring(rels,xml_declaration=True,encoding='UTF-8',standalone=True),
                  '[Content_Types].xml':etree.tostring(types,xml_declaration=True,encoding='UTF-8',standalone=True),
                  'word/fonts/aria.odttf':bytes(data)})
    with zipfile.ZipFile(path,'w',zipfile.ZIP_DEFLATED) as z:
        for name,raw in files.items():z.writestr(name,raw)


